from abc import ABC, abstractmethod
from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.application.usuarios.ports.user_repository import UserRepository
from app.domain.auth.models import Credencial, Sesion


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, encoded: str, password: str) -> bool: ...
    def needs_rehash(self, encoded: str) -> bool: ...


class TokenService(Protocol):
    def issue(self, session: Sesion) -> str: ...
    def verify(self, token: str) -> tuple[UUID, UUID]: ...


class LoginAttemptReservation(Protocol):
    def release(self) -> None: ...


class LoginAttemptLimiter(Protocol):
    def check(self, email: str, ip: str, now: datetime) -> LoginAttemptReservation: ...
    def failure(self, email: str, ip: str, now: datetime) -> None: ...
    def success(self, email: str, ip: str, attempted_at: datetime, *, reservation: LoginAttemptReservation) -> None: ...
    def cleanup(self, now: datetime) -> int: ...


class SecurityUnitOfWork(ABC):
    usuarios: UserRepository

    @abstractmethod
    def __enter__(self): ...
    @abstractmethod
    def __exit__(self, exc_type, exc, tb): ...
    @abstractmethod
    def credential(self, user_id: UUID) -> Credencial | None: ...
    @abstractmethod
    def put_credential(self, credential: Credencial) -> None: ...
    @abstractmethod
    def insert_initial_credential(self, credential: Credencial) -> None:
        """Insertar sin sobrescribir; rechazar si ya existe la credencial."""
        ...
    @abstractmethod
    def session(self, session_id: UUID) -> Sesion | None: ...
    @abstractmethod
    def put_session(self, session: Sesion) -> None: ...
    @abstractmethod
    def revoke(self, user_id: UUID, now: datetime) -> None: ...
    @abstractmethod
    def admin_provisioned(self) -> bool: ...
    @abstractmethod
    def consume(self, scope, digest, start, expires, limit) -> int: ...
    @abstractmethod
    def release_attempt(self, scope, digest, start) -> None: ...
    @abstractmethod
    def cleanup_attempts(self, now, limit=1000) -> int: ...
